export type I18nKey = keyof typeof translations.zh

export function formatString(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`))
}

export function useI18n(): { t: (key: I18nKey, params?: Record<string, string | number>) => string; lang: LocaleKey } {
  const lang = useAppStore((s) => s.uiPrefs.language) as LocaleKey
  const currentLang: LocaleKey = lang === 'en' ? 'en' : 'zh'
  const t = (key: I18nKey, params?: Record<string, string | number>): string => {
    const dict = translations[currentLang] ?? translations.zh
    const val = (dict as Record<string, string>)[key] ?? (translations.zh as Record<string, string>)[key] ?? key
    return formatString(val, params)
  }
  return { t, lang: currentLang }
}

export function getT(lang: LocaleKey = 'zh'): (key: I18nKey, params?: Record<string, string | number>) => string {
  const currentLang: LocaleKey = lang === 'en' ? 'en' : 'zh'
  return (key: I18nKey, params?: Record<string, string | number>): string => {
    const dict = translations[currentLang] ?? translations.zh
    const val = (dict as Record<string, string>)[key] ?? (translations.zh as Record<string, string>)[key] ?? key
    return formatString(val, params)
  }
}
